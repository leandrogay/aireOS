// ==== AI models ====
// When Google retires the Gemini model an AI feature uses, the backend
// (app/services/ai_models.py) answers with one sentence naming every feature on
// that model and every setting to change. That sentence arrives three ways:
// as the error `detail` of the call that failed, as `message` in
// GET /api/ai-models/status, and rebuilt here from a model_outdated
// notification's payload for the bell. No imports, so tests/aiModels.test.mjs
// runs under plain node --test.

// The name staff know each feature by (backend ai_models.FEATURES labels).
export const MODEL_FEATURES = {
  mapping: 'Nomenclature generation',
  assistant: 'Assistant',
};

/** 'mapping' → 'Nomenclature generation'; an unknown key is shown as it is. */
export function modelFeatureLabel(feature) {
  return MODEL_FEATURES[feature] || feature || 'AI feature';
}

/** 'A', 'A and B', 'A, B and C' (backend ai_models._join). */
export function joinWords(words) {
  const list = (words || []).filter(Boolean);
  if (list.length <= 1) return list.join('');
  return `${list.slice(0, -1).join(', ')} and ${list.at(-1)}`;
}

/** 'Nomenclature generation and Assistant' for a model_outdated payload's `features`. */
export function modelFeaturesText(features) {
  return joinWords((features || []).map(modelFeatureLabel)) || 'AI feature';
}

/**
 * The backend's sentence (ai_models.unavailable_message), rebuilt from a
 * model_outdated payload: `current_model`, `features`, `settings`.
 *
 * @param {{ current_model?: string, features?: string[], settings?: string[] }} payload
 */
export function modelUnavailableSentence(payload) {
  const settings = joinWords(payload?.settings) || 'its model setting';
  return (
    `The AI model ${payload?.current_model || 'in use'} is no longer available. ` +
    `It's used by ${modelFeaturesText(payload?.features)}. ` +
    `To fix this, update ${settings} to a current Gemini model and redeploy.`
  );
}

// What stops working for each feature once its model is gone, one sentence
// each. The Assistant cannot answer at all (blocking, so it comes first);
// upload mapping carries on by hand (degraded).
const IMPACT = {
  assistant: "The Assistant can't answer questions.",
  mapping: 'New upload layouts have to be mapped by hand.',
};

/**
 * The short bell wording for a retired model: what stops working, then the
 * fix. Built from a model_outdated payload (`features`, `settings`).
 *
 * @param {{ features?: string[], settings?: string[] }} payload
 */
export function modelImpactSentence(payload) {
  const features = payload?.features || [];
  const impacts = Object.keys(IMPACT)
    .filter((feature) => features.includes(feature))
    .map((feature) => IMPACT[feature]);
  const settings = joinWords(payload?.settings) || 'its model setting';
  const fix = `To fix this, update ${settings} to a current Gemini model and redeploy.`;
  return [...(impacts.length ? impacts : ['An AI feature has stopped working.']), fix].join(' ');
}

// The notice's own line; the backend sentence (which setting to change) is its detail.
const NOTICE_TEXT = {
  mapping: 'AI mapping is unavailable. New layouts have to be mapped by hand.',
  assistant: 'The Assistant is unavailable',
};

/**
 * What to show for one feature, from GET /api/ai-models/status, or null while
 * its model is available (or the status has not loaded).
 *
 * @param {Record<string, { available: boolean, message: string | null }> | null} status
 * @param {'mapping' | 'assistant'} feature
 * @returns {{ text: string, detail: string | null } | null} `detail` is the full backend sentence
 */
export function modelNotice(status, feature) {
  const entry = status?.[feature];
  if (!entry || entry.available !== false) return null;
  return {
    text: NOTICE_TEXT[feature] || `${modelFeatureLabel(feature)} is unavailable.`,
    detail: entry.message || null,
  };
}

/**
 * The one-line toast for an upload whose mapping could not be generated by AI
 * (outcome `aiUnavailable`: the mapping model is retired). When the status
 * also reports the Assistant's model retired, the toast names both. Kept
 * under the toast's ~38 characters; the notification bell carries the fix.
 *
 * @param {Record<string, { available: boolean }> | null} status GET /api/ai-models/status, or null if it could not be read
 */
export function modelToastText(status) {
  if (status?.assistant?.available === false) return 'Mapping and Assistant models outdated';
  return 'AI mapping unavailable: map by hand';
}
