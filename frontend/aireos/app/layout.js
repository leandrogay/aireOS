import { Geist_Mono, DM_Sans, DM_Serif_Display, Figtree } from "next/font/google";
import "./globals.css";
import AssistantWidget from "./components/assistant/AssistantWidget";

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
  weight: "400",
});

// AIRE brand kit: DM Sans for body/UI text, DM Serif for headings/titles
const dmSans = DM_Sans({
  variable: "--font-dm-sans",
  subsets: ["latin"],
});

// DM Sans ships no tabular figures (no `tnum` feature, "1" is half as wide as
// "0"), so `tabular-nums` does nothing in it. Figtree is the closest geometric
// sans that has them; globals.css gives it to everything marked tabular-nums.
const figtree = Figtree({
  variable: "--font-numeric",
  subsets: ["latin"],
});

const dmSerif = DM_Serif_Display({
  variable: "--font-dm-serif",
  weight: "400",
  subsets: ["latin"],
});

export const metadata = {
  title: "AireOS",
  description: "Generated by create next app",
};

export default function RootLayout({ children }) {
  return (
    <html
      lang="en"
      className={`${dmSans.variable} ${dmSerif.variable} ${geistMono.variable} ${figtree.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col font-sans">
        {children}
        <AssistantWidget />
      </body>
    </html>
  );
}
