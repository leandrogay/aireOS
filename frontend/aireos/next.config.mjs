import { loadEnvFile } from "node:process";

// This project keeps frontend variables separate from backend secrets.
loadEnvFile(new URL(".env.frontend", import.meta.url));

/** @type {import('next').NextConfig} */
const nextConfig = {
  reactCompiler: true,
  // Emits .next/standalone (server.js + only the node_modules it needs) for
  // the Cloud Run image -- see Dockerfile. `next dev` ignores it.
  output: 'standalone',
  // Deployed builds set BACKEND_API_URL (deploy/<env>/web.build.env) so the
  // web server forwards /api/* to the API: the browser then talks to one
  // origin, which the SSO session cookie needs. Locally it is unset and the
  // browser calls NEXT_PUBLIC_API_URL (localhost:8000) directly, as before.
  async rewrites() {
    const backend = (process.env.BACKEND_API_URL || '').replace(/\/$/, '');
    if (!backend) return [];
    return [{ source: '/api/:path*', destination: `${backend}/api/:path*` }];
  },
  experimental: {
    // Forwarded requests otherwise time out after 30s; an upload whose mapping
    // is generated by the model can take longer. Matches Cloud Run's default
    // 300s request timeout.
    proxyTimeout: 300_000,
    // proxy.js makes Next buffer request bodies, and a body over the limit is
    // silently cut short. 32mb is Cloud Run's own request size limit.
    proxyClientMaxBodySize: '32mb',
  },
};

export default nextConfig;
